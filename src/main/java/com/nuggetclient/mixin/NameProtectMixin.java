package com.nuggetclient.mixin;

import com.nuggetclient.player.PlayerExtras;
import net.minecraft.client.gui.hud.ChatHud;
import net.minecraft.client.gui.hud.MessageIndicator;
import net.minecraft.network.message.MessageSignatureData;
import net.minecraft.text.Text;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;

/** Name Protect: eigener Name in neuen Chat-Zeilen ersetzt. */
@Mixin(ChatHud.class)
public abstract class NameProtectMixin {

    @ModifyVariable(method = "addMessage(Lnet/minecraft/text/Text;Lnet/minecraft/network/message/MessageSignatureData;Lnet/minecraft/client/gui/hud/MessageIndicator;)V",
            at = @At("HEAD"), argsOnly = true, ordinal = 0)
    private Text nugget_client$protect(Text message) {
        return PlayerExtras.protect(message);
    }
}
