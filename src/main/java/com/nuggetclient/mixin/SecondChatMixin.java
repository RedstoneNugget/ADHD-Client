package com.nuggetclient.mixin;

import com.nuggetclient.chatplus.SecondChat;
import net.minecraft.client.gui.hud.ChatHud;
import net.minecraft.client.gui.hud.MessageIndicator;
import net.minecraft.network.message.MessageSignatureData;
import net.minecraft.text.Text;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** Second Chat: Zeilen, die nicht von Spielern kommen, in den zweiten Chat umleiten. */
@Mixin(ChatHud.class)
public abstract class SecondChatMixin {

    @Inject(method = "addMessage(Lnet/minecraft/text/Text;Lnet/minecraft/network/message/MessageSignatureData;Lnet/minecraft/client/gui/hud/MessageIndicator;)V",
            at = @At("HEAD"), cancellable = true)
    private void nugget_client$secondChat(Text message, MessageSignatureData signature, MessageIndicator indicator, CallbackInfo ci) {
        if (SecondChat.capture(message)) ci.cancel();
    }
}
